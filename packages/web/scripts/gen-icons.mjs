#!/usr/bin/env node
// Writes src/components/icon-paths.ts with only the Feather icons the app uses,
// so the client bundle never ships all 287. Add a name to ICONS and rerun:
//   pnpm --filter @hitl/web gen:icons
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const ICONS = [
  // navigation
  "activity", "bar-chart-2", "bell", "cpu", "grid", "home", "layers", "layout", "message-square",
  "trending-up", "user-check", "users", "zap",
  // readings and votes
  "droplet", "thermometer", "sun", "cloud-snow", "smile", "wind", "clock",
  // status
  "alert-circle", "alert-triangle", "check", "check-circle", "info", "wifi", "wifi-off", "x-circle",
  // actions
  "chevron-left", "chevron-right", "download", "edit-3", "external-link", "eye", "filter", "key",
  "lock", "log-in", "log-out", "mail", "phone", "play", "plus", "refresh-cw", "save", "send", "trash-2", "x",
  "user", "shield", "map-pin", "database", "server", "box",
];

const require = createRequire(import.meta.url);
const all = require("feather-icons/dist/icons.json");
const missing = ICONS.filter((n) => !(n in all));
if (missing.length) throw new Error(`Not Feather icons: ${missing.join(", ")}`);

const body = ICONS.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(all[n])},`).join("\n");
writeFileSync(
  new URL("../src/components/icon-paths.ts", import.meta.url),
  `// Generated by scripts/gen-icons.mjs from feather-icons (MIT). Do not edit by hand.\n` +
    `export const ICON_PATHS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICON_PATHS;\n`,
);
console.log(`Wrote ${ICONS.length} icons.`);
